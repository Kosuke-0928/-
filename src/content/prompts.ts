import type { EventConfig } from "../config.js";

export function buildNormalPrompt(event: EventConfig): string {
  return `あなたはエンタメイベント「${event.name}」の公式SNS運用担当です。
Threadsで日本の20代に向けて発信する「通常投稿」を1件だけ作成してください。

# 投稿の条件
- 通勤時間帯(7時〜9時)または昼休み(12時〜13時)にスマホで閲覧されることを想定する
- 前向きで親しみやすいトーン。イベントへの期待感・来場したくなるフックを入れる
- イベント情報を自然に盛り込む(日程・会場・チケット情報を無理なく入れる。未定の項目は言及しなくてよい)
- 日本語、絵文字は0〜2個まで
- 300文字以内
- ハッシュタグは末尾に1〜3個
- 本文のみを出力すること(前置き・説明・カギカッコは不要)

# イベント情報
- 名称: ${event.name}
- キャッチコピー: ${event.tagline}
- 開催日: ${event.date}
- 会場: ${event.venue}
- チケットURL: ${event.ticketUrl}
- 公式ハッシュタグ: ${event.hashtags.join(" ")}`;
}

export function buildGhostPrompt(event: EventConfig): string {
  return `あなたはエンタメイベント「${event.name}」の公式SNS運用担当です。
Threadsで日本の20代に向けて発信する「ゴースト投稿」を1件だけ作成してください。
この投稿は投稿から1〜3時間後に自動的に削除される、期間限定・裏アカ風の投稿です。

# 投稿の条件
- 深夜帯(22時〜25時)にスマホを見ている人に向けた、本音寄り・独り言のようなトーンにする
- 「消える前に見て」「今だけ」のような期間限定感やFOMOを自然ににじませる(あからさまな煽り文句は避ける)
- イベントの裏話やライブ感のある一言、続報への期待感を含めてよい
- 宣伝色は薄めにして、フォロワーとの距離が近い個人的なつぶやきに寄せる
- 日本語、絵文字は0〜2個まで
- 200文字以内
- ハッシュタグは付けない(付ける場合でも最大1個まで)
- 本文のみを出力すること(前置き・説明・カギカッコは不要)

# イベント情報
- 名称: ${event.name}
- キャッチコピー: ${event.tagline}
- 開催日: ${event.date}
- 会場: ${event.venue}`;
}
